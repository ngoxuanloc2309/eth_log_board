#!/usr/bin/env python3

import base64
import gzip
import sys
from pathlib import Path


ASSETS = (
    ("index.html", "web_server_index_html_gzip", True),
    ("styles.css", "web_server_styles_css_gzip", True),
    ("app.js", "web_server_app_js_gzip", True),
    ("X-favicon.png", "web_server_favicon_png", False),
)


def render_array(name: str, data: bytes) -> str:
    rows = []
    for offset in range(0, len(data), 12):
        row = ", ".join(f"0x{value:02X}U" for value in data[offset : offset + 12])
        rows.append(f"    {row},")
    return (
        f"static const uint8_t {name}[] = {{\n"
        + "\n".join(rows)
        + "\n};\n"
        + f"static const size_t {name}_length = sizeof({name});\n"
    )


def render_index(source_directory: Path) -> bytes:
    html = (source_directory / "index.html").read_bytes()
    stylesheet = (source_directory / "styles.css").read_bytes()
    app_script = (source_directory / "app.js").read_bytes()
    favicon = base64.b64encode(
        (source_directory / "X-favicon.png").read_bytes()
    )
    favicon_uri = b"data:image/png;base64," + favicon
    expected_replacements = (
        (
            b'<link rel="stylesheet" href="/styles.css">',
            b"<style>\n" + stylesheet + b"\n</style>",
        ),
        (
            b'<script src="/app.js" defer></script>',
            b'<script type="module">\n' + app_script + b"\n</script>",
        ),
        (b'href="/X-favicon.png"', b'href="' + favicon_uri + b'"'),
        (b'src="/X-favicon.png"', b'src="' + favicon_uri + b'"'),
    )
    for source, replacement in expected_replacements:
        if html.count(source) != 1:
            raise ValueError(f"Expected one {source.decode(errors='replace')} in index.html")
        html = html.replace(source, replacement)
    return html


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: generate_assets.py ASSET_DIRECTORY OUTPUT_HEADER", file=sys.stderr)
        return 2

    source_directory = Path(sys.argv[1])
    output_path = Path(sys.argv[2])
    sections = [
        "/* Generated by tools/generate_assets.py; edit source assets, not this file. */",
        "#ifndef WEB_SERVER_ASSETS_H",
        "#define WEB_SERVER_ASSETS_H",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
    ]
    for filename, symbol, compress in ASSETS:
        data = (
            render_index(source_directory)
            if filename == "index.html"
            else (source_directory / filename).read_bytes()
        )
        if compress:
            data = gzip.compress(data, compresslevel=9, mtime=0)
        sections.append(render_array(symbol, data))
    sections.extend(("#endif", ""))
    output_path.write_text("\n".join(sections), encoding="ascii")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
